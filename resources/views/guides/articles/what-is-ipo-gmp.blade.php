<p><strong>IPO GMP (grey market premium)</strong> is the premium over the issue price at which an IPO's shares change hands unofficially before they list on the stock exchange. Investors watch it as a quick read of demand: a high GMP suggests the market expects a strong listing, while a negative GMP suggests the shares may list below the issue price.</p>

<h2 id="how-grey-market-works">How the IPO grey market works</h2>
<p>The grey market is an informal network of dealers who trade IPO shares and applications before listing, outside the stock exchanges. Deals are based on trust and settled in cash after listing. SEBI does not regulate or recognise this market, so there is no investor protection and no legal recourse if someone defaults.</p>

<h2 id="calculate-listing-price">How to calculate the expected listing price from GMP</h2>
<p>Two simple formulas turn GMP into numbers you can use:</p>
<ul>
    <li><strong>Expected listing price</strong> = upper price band + GMP</li>
    <li><strong>Expected listing gain %</strong> = GMP ÷ upper price band × 100</li>
</ul>
<p><em>Example:</em> an IPO with a price band of ₹190–200 and a GMP of ₹50 has an expected listing price of ₹250, a 25% gain. With a lot of 75 shares, that is an expected profit of ₹3,750 per lot before tax. Try it with any IPO in the <a href="{{ route('calculators.show', 'ipo-gmp') }}">IPO GMP calculator</a>.</p>

<h2 id="kostak-subject-to-sauda">Kostak and Subject to Sauda</h2>
<p>Besides GMP, you may see two other grey-market quotes:</p>
<ul>
    <li><strong>Kostak rate:</strong> a fixed amount a dealer pays you for your IPO application, whether or not you get an allotment.</li>
    <li><strong>Subject to Sauda:</strong> a price paid for your application only if it gets an allotment.</li>
</ul>
<p>Both require you to hand over control of your application to an unregulated dealer, which carries real risk.</p>

<h2 id="what-moves-gmp">What moves the GMP</h2>
<ul>
    <li><strong>Subscription numbers:</strong> heavy QIB and NII demand usually pushes GMP up.</li>
    <li><strong>Overall market mood:</strong> a falling Nifty or Sensex often drags IPO GMPs down with it.</li>
    <li><strong>Valuation and fundamentals:</strong> pricing relative to listed peers, growth and profitability.</li>
    <li><strong>Anchor book:</strong> the quality of anchor investors announced a day before the issue opens.</li>
    <li><strong>Size of the issue:</strong> smaller floats, especially SME IPOs, can see sharper swings.</li>
</ul>

<h2 id="is-gmp-reliable">How reliable is GMP?</h2>
<p>GMP is a useful sentiment indicator but a poor guarantee. It can change sharply in the last two days before listing, and it is easy to influence because volumes are small and nothing is reported. Many IPOs have listed well below their peak GMP, and some with a modest GMP have listed strongly. Treat GMP as one signal alongside the prospectus, valuation, financials and subscription data.</p>

<h2 id="using-gmp-well">Using GMP sensibly</h2>
<ul>
    <li>Watch the <strong>trend</strong>, not a single number. Each IPO page on IPO Darbaar shows the day-by-day GMP trend.</li>
    <li>Check whether the GMP holds up after the issue closes and the final subscription is known.</li>
    <li>Never apply to an IPO only because of a high GMP, and never trade in the grey market.</li>
</ul>
