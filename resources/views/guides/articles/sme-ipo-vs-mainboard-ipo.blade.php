<h2 id="minimum-investment">Why SME IPOs need more money</h2>
<p>SME lot sizes are set so that each application is worth a meaningful amount, and individual investors must apply for at least two lots. That typically puts the minimum SME application above ₹2 lakh, compared with around ₹15,000 for a mainboard IPO. Check the exact amounts on each IPO page or with the <a href="{{ route('calculators.show', 'ipo-application') }}">IPO application calculator</a>.</p>

<h2 id="regulation">Regulation and disclosure</h2>
<p>Mainboard offer documents are reviewed by SEBI. SME offer documents are reviewed by the exchange, and disclosure requirements are lighter. In 2025 SEBI tightened the SME framework, including a profitability track-record requirement for issuers and a cap on how much existing shareholders can sell through the IPO, after concerns about some small issues.</p>

<h2 id="risks">Risks specific to SME IPOs</h2>
<ul>
    <li><strong>Liquidity:</strong> shares trade in lots, and there may be few buyers when you want to sell.</li>
    <li><strong>Volatility:</strong> small floating stock can produce very large listing gains or losses.</li>
    <li><strong>Information:</strong> smaller companies have less analyst coverage and shorter track records.</li>
    <li><strong>Grey market hype:</strong> SME GMPs can be extreme and change fast; see <a href="{{ route('guides.show', 'what-is-ipo-gmp') }}">how reliable GMP is</a>.</li>
</ul>

<h2 id="migration">Can an SME company move to the main board?</h2>
<p>Yes. After it grows and meets the exchange's migration criteria, an SME-listed company can migrate to the main board, which usually improves liquidity.</p>

