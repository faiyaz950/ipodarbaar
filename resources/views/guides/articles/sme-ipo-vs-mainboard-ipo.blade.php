<p>Indian IPOs come in two kinds: <strong>mainboard IPOs</strong>, which list on the main boards of NSE and BSE, and <strong>SME IPOs</strong>, which list on the dedicated small-and-medium-enterprise platforms, NSE Emerge and BSE SME. They look similar in your broker app, but the rules, the money you need and the risks are quite different.</p>

