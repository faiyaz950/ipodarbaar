<p>When you apply for an IPO through UPI or ASBA, your money is not taken straight away. The bid amount is <strong>blocked</strong> in your bank account. If you don't get shares, the block is removed and the money is free to use again. That release is what most people call the IPO "refund".</p>

<h2 id="when">When is the money released?</h2>
<p>Under SEBI's T+3 timeline (T is the day the IPO closes):</p>
<table>
    <thead><tr><th>Day</th><th>What happens</th></tr></thead>
    <tbody>
        <tr><td>T</td><td>The IPO closes at 5 PM.</td></tr>
        <tr><td>T+1</td><td>Basis of allotment is finalised. Many banks start releasing blocked amounts the same evening.</td></tr>
        <tr><td>T+2</td><td>Blocked amounts of applicants who got no shares are released, and shares are credited to allottees' demat accounts.</td></tr>
        <tr><td>T+3</td><td>The shares list on the stock exchange.</td></tr>
    </tbody>
</table>
<p>If you were allotted shares, only the amount for those shares is debited. When you applied for more than one lot and got fewer, the rest of the blocked amount is released.</p>

<h2 id="check">How to check that the money is released</h2>
<ul>
    <li><strong>UPI:</strong> open the UPI app you used and look at the IPO mandate. It shows as revoked, or as executed if shares were allotted.</li>
    <li><strong>Net banking or bank statement:</strong> the blocked or lien amount disappears from your available balance.</li>
    <li><strong>Allotment status:</strong> check the result on the registrar's website. See <a href="{{ route('guides.show', 'how-to-check-ipo-allotment-status') }}">how to check IPO allotment status</a> or the live <a href="{{ route('ipos.allotment') }}">IPO allotment status</a> page for registrar links.</li>
</ul>

<h2 id="late">What to do if the money is not released</h2>
<ol>
    <li><strong>Wait until the end of T+2.</strong> Some banks release blocks late in the day.</li>
    <li><strong>Contact your bank</strong> (the one whose account was blocked) with the IPO name and your UPI or ASBA application reference. Releasing the block is the bank's job.</li>
    <li><strong>Contact the registrar</strong> of the IPO with your application number and PAN if the bank says it has not received the instruction.</li>
    <li><strong>Escalate to SEBI</strong> on the SCORES complaint portal if the problem is still not solved. SEBI rules require banks to compensate investors for delays in unblocking beyond the timeline.</li>
</ol>

<h2 id="tips">Avoid problems next time</h2>
<ul>
    <li>Approve the UPI mandate as soon as it arrives, and before 5 PM on the closing day.</li>
    <li>Apply once per PAN. Duplicate applications are rejected.</li>
    <li>Keep the application confirmation or UPI reference until the money is released.</li>
</ul>
