<p>Many broker apps let you "pre-apply" for an IPO: you place your bid a few days before the issue opens, and the broker submits it for you once bidding starts. It is a convenience feature that makes sure you don't forget to apply.</p>

<h2 id="how">How pre-apply works</h2>
<ol>
    <li>The IPO appears in your broker app with an "upcoming" or "pre-apply" tag once the price band is known.</li>
    <li>You choose the number of lots and bid at the cut-off price, as in a normal application.</li>
    <li>The broker holds the bid and sends it to the stock exchange when the issue opens.</li>
    <li>Your UPI app then receives the mandate request. <strong>Approve it</strong>: the bid counts only after the mandate is approved.</li>
</ol>

<h2 id="mandate">When does the UPI mandate arrive?</h2>
<p>After the broker uploads the bid to the exchange, usually on the opening day. It can take from a few minutes to a few hours. You have until 5 PM on the closing day to approve it. If no mandate arrives by the second day, check the bid status in your broker app and contact the broker.</p>

<h2 id="chances">Does pre-applying improve allotment chances?</h2>
<p>No. In an oversubscribed IPO, retail allotment is decided by a lottery among all valid applications; applying first gives no advantage. What matters is that your application is valid and the mandate is approved in time. See <a href="{{ route('guides.show', 'how-ipo-allotment-works') }}">how IPO allotment works</a>.</p>

<h2 id="change">Changing or cancelling a pre-applied bid</h2>
<p>You can modify or cancel the bid from your broker app until the issue closes. If you cancel after approving the mandate, the blocked amount is released.</p>

<h2 id="tips">Tips</h2>
<ul>
    <li>Bid at the <a href="{{ route('guides.show', 'ipo-cut-off-price') }}">cut-off price</a> so your bid stays valid whatever the final price.</li>
    <li>Keep enough balance in the linked bank account for the full amount.</li>
    <li>Track opening dates on the <a href="{{ route('ipos.upcoming') }}">upcoming IPOs</a> page or add them to your calendar from any IPO page.</li>
</ul>
