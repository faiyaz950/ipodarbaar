<p>Anchor investors are large institutions, such as mutual funds, insurance companies and foreign portfolio investors, that commit to buy a part of an IPO before it opens to the public. Their participation is disclosed on the eve of the issue and is often read as a signal of institutional interest.</p>

<h2 id="rules">How the anchor portion works</h2>
<ul>
    <li><strong>Who:</strong> qualified institutional buyers (QIBs).</li>
    <li><strong>When:</strong> anchor shares are allotted one working day before the IPO opens.</li>
    <li><strong>How much:</strong> up to 60% of the QIB portion of an IPO can go to anchors, and one-third of the anchor portion is reserved for domestic mutual funds.</li>
    <li><strong>Minimum:</strong> each anchor investor must apply for at least ₹10 crore.</li>
    <li><strong>Price:</strong> anchors buy at the anchor price. If the final issue price is higher, they pay the difference; if it is lower, they do not get the difference back.</li>
</ul>

<h2 id="lock-in">The anchor lock-in period</h2>
<table>
    <thead><tr><th>Share of anchor allotment</th><th>Locked in for</th></tr></thead>
    <tbody>
        <tr><td>50%</td><td>30 days from the date of allotment</td></tr>
        <tr><td>50%</td><td>90 days from the date of allotment</td></tr>
    </tbody>
</table>
<p>Until the lock-in ends, anchor investors cannot sell those shares. Each IPO page on IPO Darbaar shows the anchor amount and both lock-in end dates when anchor details are available.</p>

<h2 id="expiry">What happens when the lock-in ends?</h2>
<p>More shares become free to trade. If some anchors choose to sell, it can add selling pressure around the 30- and 90-day dates, especially in stocks that have risen sharply since listing. But expiry does not force anyone to sell, and many anchors hold on. The share price still depends mainly on the company's results and the market.</p>

