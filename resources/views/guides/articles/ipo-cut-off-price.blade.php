<p>Most Indian IPOs are <strong>book-built</strong>: the company announces a price band, for example ₹190 – 200, and the final issue price is set within it after bidding closes. When you tick the <strong>cut-off</strong> box on your application, you agree to buy at whatever that final price turns out to be.</p>

<h2 id="who">Who can bid at the cut-off price?</h2>
<table>
    <thead><tr><th>Investor category</th><th>Cut-off allowed?</th></tr></thead>
    <tbody>
        <tr><td>Retail individual investors (bids up to ₹2 lakh)</td><td>Yes</td></tr>
        <tr><td>Eligible employees and shareholders in their reserved quotas</td><td>Yes</td></tr>
        <tr><td>Non-institutional investors (HNIs, above ₹2 lakh)</td><td>No, they bid at a specific price</td></tr>
        <tr><td>Qualified institutional buyers and anchor investors</td><td>No</td></tr>
    </tbody>
</table>

<h2 id="blocked">Why is the upper band blocked?</h2>
<p>At the time you apply, the final price is not known. So when you bid at cut-off, the amount at the upper end of the band is blocked: lots × lot size × upper price. Work out the amount with the <a href="{{ route('calculators.show', 'ipo-application') }}">IPO application amount calculator</a>.</p>
<p>If the final price is set below the upper band, the difference is released after allotment. In practice, most issues are priced at the upper end.</p>

<h2 id="why">Why bid at cut-off?</h2>
<ul>
    <li><strong>Your bid stays valid.</strong> A bid below the final issue price is rejected. At cut-off, it is always at the final price.</li>
    <li><strong>No guesswork.</strong> You don't have to predict where the price will be fixed.</li>
    <li><strong>You pay the same as everyone.</strong> All successful retail applicants pay the final issue price.</li>
</ul>

<h2 id="fixed">Fixed-price issues</h2>
<p>Some IPOs, especially smaller SME issues, have a single fixed price instead of a band. There is nothing to choose: you bid at that price.</p>
