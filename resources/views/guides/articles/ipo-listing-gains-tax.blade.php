<p>Profits from selling IPO shares are taxable. For most investors they are <strong>capital gains</strong>, and the rate depends on how long you held the shares. The rates below apply to listed equity shares sold on a stock exchange (with securities transaction tax paid) from 23 July 2024 onwards.</p>

<h2 id="rates">Tax rates on IPO gains</h2>
<table>
    <thead><tr><th>Holding period</th><th>Type</th><th>Tax rate</th></tr></thead>
    <tbody>
        <tr><td>12 months or less (including selling on listing day)</td><td>Short-term capital gain (STCG)</td><td>20% plus 4% cess</td></tr>
        <tr><td>More than 12 months</td><td>Long-term capital gain (LTCG)</td><td>12.5% on gains above ₹1.25 lakh a year, plus 4% cess</td></tr>
    </tbody>
</table>
<p>Surcharge applies at higher income levels. The holding period starts on the date the shares are allotted, not the day you applied.</p>

<h2 id="example">Worked example: selling on listing day</h2>
<p>You are allotted one lot of 100 shares at ₹200 and sell all of them on listing day at ₹260.</p>
<ul>
    <li>Sale value: 100 × ₹260 = ₹26,000</li>
    <li>Cost: 100 × ₹200 = ₹20,000</li>
    <li>Short-term capital gain: ₹6,000 (brokerage and charges can be deducted as transfer expenses)</li>
    <li>Tax at 20%: ₹1,200, plus 4% cess (₹48) = <strong>₹1,248</strong></li>
</ul>
