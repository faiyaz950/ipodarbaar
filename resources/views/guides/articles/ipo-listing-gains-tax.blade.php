<h2 id="losses">If the IPO lists at a loss</h2>
<p>A short-term capital loss can be set off against short-term and long-term capital gains in the same year. Any unused loss can be carried forward for up to eight years, provided you file your income tax return by the due date.</p>

<h2 id="business-income">When IPO gains become business income</h2>
<p>If you apply for IPOs and flip them frequently as a regular activity, the income tax department may treat the profits as business income, taxed at your slab rate. The frequency of trades, the volume and your intention matter. If you are unsure, speak to a tax professional.</p>

<h2 id="filing">Reporting IPO gains in your return</h2>
<ul>
    <li>Individuals with capital gains and no business income usually file <strong>ITR-2</strong>; those reporting business income file <strong>ITR-3</strong>.</li>
    <li>Your broker's capital gains statement lists each sale with its purchase and sale values.</li>
    <li>If your total tax for the year crosses ₹10,000, pay advance tax on capital gains in the instalment after the gain arises to avoid interest.</li>
</ul>
<p class="callout">This guide explains general rules and is not tax advice. Tax laws change with each Budget; check the latest rules or ask a chartered accountant before filing.</p>
