<p>If you got an allotment, you can sell the shares from the moment they list. This guide covers when the shares reach your demat account, how the listing-day session works and how to place the sell order. See today's listings on the <a href="{{ route('ipos.listing-today') }}">IPO listing today</a> page.</p>

<h2 id="credit">When do the shares reach your demat account?</h2>
<p>Under SEBI's T+3 timeline, allotted shares are credited on <strong>T+2</strong>, usually by the evening, and the IPO lists on <strong>T+3</strong>. By the morning of listing day the shares show in your broker app's holdings, sometimes with the price shown as zero until trading starts.</p>

<h2 id="session">How listing day works</h2>
<table>
    <thead><tr><th>Time</th><th>What happens</th></tr></thead>
    <tbody>
        <tr><td>9:00 – 9:45 AM</td><td>Special pre-open session: buy and sell orders are collected.</td></tr>
        <tr><td>9:45 – 10:00 AM</td><td>Orders are matched and the opening (listing) price is set.</td></tr>
        <tr><td>10:00 AM onwards</td><td>Normal trading starts, within a price band set by the exchange.</td></tr>
    </tbody>
</table>

<h2 id="steps">How to sell, step by step</h2>
<ol>
    <li><strong>Open your holdings</strong> in the broker app and find the IPO shares.</li>
    <li><strong>Choose sell</strong>, select delivery (CNC) and enter the quantity.</li>
    <li><strong>Use a limit order</strong> so you control the lowest price you accept. Listing-day prices can move fast.</li>
    <li><strong>Authorise the sale.</strong> Approve it with your CDSL TPIN or NSDL OTP (eDIS), unless you have already given your broker a DDPI.</li>
    <li><strong>Place the order</strong> in the pre-open window (9:00 – 9:45 AM) or any time after 10:00 AM, and check the order book to see that it went through.</li>
</ol>

<h2 id="sme">Selling SME IPO shares</h2>
<p>SME stocks trade in lots. You can only sell in multiples of the lot size, and a market maker quotes prices for three years after listing. Trading can be thin, so a limit order matters even more.</p>

<h2 id="choices">Sell, hold or split?</h2>
<p>There is no rule. Some investors sell on listing day, some hold for the long term, and some sell part and keep the rest. Compare the listing price with your reasons for applying and the company's fundamentals. IPO Darbaar does not give buy or sell advice.</p>

<h2 id="money">Charges and tax</h2>
<p>Selling attracts STT, brokerage, exchange charges, GST and a DP charge, and the gain is a short-term capital gain taxed at 20% plus cess. See what you keep with the <a href="{{ route('calculators.show', 'ipo-net-proceeds') }}">IPO net proceeds calculator</a>, and read more on <a href="{{ route('guides.show', 'ipo-listing-gains-tax') }}">tax on IPO listing gains</a>.</p>
