<h2 id="drhp">DRHP: the draft for review</h2>
<p>The company and its lead managers file the DRHP to have the offer reviewed. It is published for public comments, and SEBI then issues its observations. If the company makes material changes, it files an updated draft (UDRHP). A company usually has twelve months from SEBI's observations to open the issue.</p>

<h2 id="rhp">RHP: the document to read before you apply</h2>
<p>The RHP is filed with the Registrar of Companies before the issue opens. It has everything investors need except the final price and the exact number of shares, which is why it is called a "red herring" prospectus. The price band is announced in a separate advertisement at least two working days before the issue opens.</p>

<h2 id="prospectus">Prospectus: the final version</h2>
<p>After bidding closes and the price is fixed, the company files the prospectus with the final issue price and issue size.</p>

<h2 id="read">What to read in the RHP</h2>
<ul>
    <li><strong>Objects of the issue:</strong> what the fresh money will be used for, and how much of the IPO is an offer for sale by existing shareholders.</li>
    <li><strong>Risk factors:</strong> the company's own list of what could go wrong.</li>
    <li><strong>Financial information:</strong> revenue, profit, debt and cash flows for recent years.</li>
    <li><strong>Basis for offer price:</strong> EPS, return ratios and the valuation of listed peers. Check it with the <a href="{{ route('calculators.show', 'pe-ratio') }}">P/E ratio calculator</a>.</li>
    <li><strong>Outstanding litigation</strong> and <strong>promoter holding</strong> before and after the issue.</li>
</ul>

<h2 id="where">Where to find the documents</h2>
<p>Offer documents are published on the SEBI website under public issue filings, on the NSE and BSE websites, and on the websites of the company and its lead managers. IPO pages on IPO Darbaar link to the RHP when it is available.</p>
